CREATE DATABASE IF NOT EXISTS casa_hacker_projeto_membros CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE casa_hacker_projeto_membros;

SET NAMES utf8mb4;

CREATE TABLE projeto (
 codigo VARCHAR(16) NOT NULL PRIMARY KEY,
 nome VARCHAR(255) NOT NULL,programa VARCHAR(120),situacao VARCHAR(40),
 data_inicio DATE,data_fim DATE,
 CONSTRAINT ck_datas_projeto CHECK (data_fim IS NULL OR data_inicio IS NULL OR data_fim>=data_inicio)
) ENGINE=InnoDB;

CREATE TABLE identidade_genero (
 id INT UNSIGNED NOT NULL PRIMARY KEY,
 descricao VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE sexo (
 id INT UNSIGNED NOT NULL PRIMARY KEY,
 descricao VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE cor_raca_etnia (
 id INT UNSIGNED NOT NULL PRIMARY KEY,
 descricao VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE renda_casa (
 id INT UNSIGNED NOT NULL PRIMARY KEY,
 descricao VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE renda_por_pessoa (
 id INT UNSIGNED NOT NULL PRIMARY KEY,
 descricao VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE escolaridade (
 id INT UNSIGNED NOT NULL PRIMARY KEY,
 descricao VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE faixa_etaria (
 id INT UNSIGNED NOT NULL PRIMARY KEY,
 descricao VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE localizacao_cep (
 id INT UNSIGNED NOT NULL PRIMARY KEY,descricao VARCHAR(120) NOT NULL UNIQUE,
 cep CHAR(8),municipio VARCHAR(120),latitude DECIMAL(9,6),longitude DECIMAL(9,6),
 origem VARCHAR(120) NOT NULL,
 CONSTRAINT ck_latitude CHECK (latitude BETWEEN -90 AND 90),
 CONSTRAINT ck_longitude CHECK (longitude BETWEEN -180 AND 180),
 CONSTRAINT ck_par_coordenadas CHECK ((latitude IS NULL AND longitude IS NULL) OR (latitude IS NOT NULL AND longitude IS NOT NULL))
) ENGINE=InnoDB;

CREATE TABLE membro (
 id INT UNSIGNED NOT NULL PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 id_identidade_genero INT UNSIGNED NOT NULL,
 id_sexo INT UNSIGNED NOT NULL,
 id_cor_raca_etnia INT UNSIGNED NOT NULL,
 id_renda_casa INT UNSIGNED NOT NULL,
 id_renda_por_pessoa INT UNSIGNED NOT NULL,
 id_escolaridade INT UNSIGNED NOT NULL,
 id_faixa_etaria INT UNSIGNED NOT NULL,
 id_localizacao_cep INT UNSIGNED NOT NULL,
 CONSTRAINT fk_membro_identidade_genero FOREIGN KEY(id_identidade_genero) REFERENCES identidade_genero(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_membro_sexo FOREIGN KEY(id_sexo) REFERENCES sexo(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_membro_cor_raca_etnia FOREIGN KEY(id_cor_raca_etnia) REFERENCES cor_raca_etnia(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_membro_renda_casa FOREIGN KEY(id_renda_casa) REFERENCES renda_casa(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_membro_renda_por_pessoa FOREIGN KEY(id_renda_por_pessoa) REFERENCES renda_por_pessoa(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_membro_escolaridade FOREIGN KEY(id_escolaridade) REFERENCES escolaridade(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_membro_faixa_etaria FOREIGN KEY(id_faixa_etaria) REFERENCES faixa_etaria(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_membro_localizacao_cep FOREIGN KEY(id_localizacao_cep) REFERENCES localizacao_cep(id) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE inscricao (
 id INT UNSIGNED NOT NULL PRIMARY KEY,
 codigo_projeto VARCHAR(16) NOT NULL,id_membro INT UNSIGNED NOT NULL,
 data_inscricao DATE NOT NULL,situacao VARCHAR(30) NOT NULL,
 CONSTRAINT uq_inscricao_projeto_membro UNIQUE(codigo_projeto,id_membro),
 CONSTRAINT fk_inscricao_projeto FOREIGN KEY(codigo_projeto) REFERENCES projeto(codigo) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_inscricao_membro FOREIGN KEY(id_membro) REFERENCES membro(id) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

