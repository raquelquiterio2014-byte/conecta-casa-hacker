CREATE VIEW vw_totais_projeto AS
SELECT p.codigo AS codigo_projeto,p.nome,COUNT(i.id) AS total_inscricoes_simuladas
FROM projeto p LEFT JOIN inscricao i ON i.codigo_projeto=p.codigo
GROUP BY p.codigo,p.nome;

CREATE VIEW vw_distancias_membros AS
SELECT i.id AS id_inscricao,i.codigo_projeto,m.id AS id_membro,m.nome AS membro_ficticio,
 l.id AS id_localizacao,l.descricao AS localizacao,l.cep,l.municipio,l.latitude,l.longitude,l.origem,
 CASE WHEN l.latitude IS NULL OR l.longitude IS NULL THEN NULL
 ELSE 6371*2*ASIN(SQRT(LEAST(1,GREATEST(0,
 POWER(SIN(RADIANS(l.latitude-(-22.908246))/2),2)+
 COS(RADIANS(-22.908246))*COS(RADIANS(l.latitude))*
 POWER(SIN(RADIANS(l.longitude-(-47.066752))/2),2))))) END AS distancia_km
FROM inscricao i JOIN membro m ON m.id=i.id_membro
JOIN localizacao_cep l ON l.id=m.id_localizacao_cep;